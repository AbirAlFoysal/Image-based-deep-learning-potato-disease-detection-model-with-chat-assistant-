"""
Helper functions for Dr. Pato AI Assistant.
Contains utility functions for common responses.
"""


def get_off_topic_response():
    """
    Generate a polite response for off-topic questions.
    
    Returns:
        str: A response redirecting to potato-related topics
    """
    return "I specialize only in potato diseases. Please ask me about potato blight, scab, wilt, rot, or other potato health issues."


def get_image_analysis_encouragement():
    """
    Generate an encouraging response about image analysis capabilities.
    
    Returns:
        str: A response encouraging users to upload images
    """
    return "Yes, I can analyze potato tuber images. Please upload a clear photo of the affected tuber, and I'll help identify possible diseases or damage."
